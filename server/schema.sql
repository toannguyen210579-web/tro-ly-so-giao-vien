CREATE TABLE IF NOT EXISTS counters (k TEXT PRIMARY KEY, n INTEGER NOT NULL DEFAULT 0, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS flags (k TEXT PRIMARY KEY, v TEXT);
CREATE INDEX IF NOT EXISTS counters_exp ON counters (exp);
CREATE TABLE IF NOT EXISTS reports (id INTEGER PRIMARY KEY AUTOINCREMENT, device TEXT NOT NULL, mode TEXT, input TEXT, output TEXT, reason TEXT, created INTEGER NOT NULL, exp INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS reports_exp ON reports (exp);
CREATE INDEX IF NOT EXISTS reports_device ON reports (device);
